import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { buildDatabase } from '../build';
import {
  CURATED_DIR,
  DATA_DB_FILE,
  DIST_DIR,
  GENERATED_MANIFEST_TS,
  MEDIA_LISTING_FILE,
  MOBILE_DB_DIR,
  POKEAPI_CSV_DIR,
  SIZE_FAIL_BYTES,
  SIZE_WARN_BYTES,
} from '../config';
import type { BuildReport } from '../finalize';

const mb = (bytes: number) => `${(bytes / 1024 / 1024).toFixed(2)} MB`;

function printSizes(report: BuildReport): void {
  if (!report.sizes) {
    console.log('  (dbstat unavailable — no per-table size report)');
    return;
  }
  console.log('\nSize by table (data + indexes):');
  for (const size of report.sizes.slice(0, 15)) {
    const marker = size.table === 'pokemon_moves' ? '  <== pokemon_moves' : '';
    console.log(
      `  ${size.table.padEnd(32)} ${mb(size.totalBytes).padStart(10)}  ${String(size.pct).padStart(5)}%` +
        `  (indexes ${mb(size.indexBytes)})${marker}`,
    );
  }
}

function writeGeneratedManifest(report: BuildReport): void {
  const source = `// Generated by @thedex/data-pipeline (\`pnpm data:build\`). Do not edit.
export const DATA_MANIFEST = {
  dataVersion: '${report.dataVersion}',
  schemaVersion: ${report.schemaVersion},
  pokeapiSha: '${report.pokeapiSha}',
  pkmnVersion: '${report.pkmnVersion}',
  spritesSha: '${report.spritesSha}',
  criesSha: '${report.criesSha}',
} as const;

export const DATA_VERSION: string = DATA_MANIFEST.dataVersion;
`;
  writeFileSync(GENERATED_MANIFEST_TS, source);
}

const started = performance.now();
const options = {
  csvDir: POKEAPI_CSV_DIR,
  curatedDir: CURATED_DIR,
  mediaListingFile: MEDIA_LISTING_FILE,
  outFile: path.join(DIST_DIR, DATA_DB_FILE),
  dedupeLearnsets: process.argv.includes('--dedupe-learnsets'),
};

let report = buildDatabase(options);
if (
  report.sizeBytes > SIZE_FAIL_BYTES &&
  !options.dedupeLearnsets &&
  report.learnsetDedupePotential > 0
) {
  console.warn(
    `\n! ${mb(report.sizeBytes)} exceeds the ${mb(SIZE_FAIL_BYTES)} budget — rebuilding with per-game learnset dedupe`,
  );
  report = buildDatabase({ ...options, dedupeLearnsets: true });
}

printSizes(report);
writeFileSync(path.join(DIST_DIR, 'manifest.json'), `${JSON.stringify(report, null, 2)}\n`);
writeGeneratedManifest(report);
mkdirSync(MOBILE_DB_DIR, { recursive: true });
copyFileSync(report.file, path.join(MOBILE_DB_DIR, DATA_DB_FILE));

console.log(
  `\n${DATA_DB_FILE}: ${mb(report.sizeBytes)} · data_version ${report.dataVersion}` +
    `${report.dedupeLearnsets ? ' · learnsets deduped' : ''} · ${((performance.now() - started) / 1000).toFixed(1)}s`,
);
if (report.sizeBytes > SIZE_WARN_BYTES) {
  console.warn(
    `! Above the ${mb(SIZE_WARN_BYTES)} warning budget ` +
      `(per-game learnset dedupe would remove ${report.learnsetDedupePotential} rows)`,
  );
}
if (report.sizeBytes > SIZE_FAIL_BYTES) {
  console.error(`✗ ${mb(report.sizeBytes)} exceeds the hard budget of ${mb(SIZE_FAIL_BYTES)}`);
  process.exitCode = 1;
}
