/**
 * Turns drizzle-kit's user-DB migrations into a plain TS module (SQL as strings), so the
 * same bundle works in Metro, Vitest and a future Tauri app without babel inline-import.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

interface Journal {
  entries: { idx: number; tag: string }[];
}

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const migrationsDir = path.join(root, 'migrations', 'user');
const target = path.join(root, 'src', 'schema', 'user', 'migrations.generated.ts');

const journal = JSON.parse(
  await readFile(path.join(migrationsDir, 'meta', '_journal.json'), 'utf8'),
) as Journal;

const entries = await Promise.all(
  journal.entries.map(async (entry) => {
    const sqlText = await readFile(path.join(migrationsDir, `${entry.tag}.sql`), 'utf8');
    const key = `m${String(entry.idx).padStart(4, '0')}`;
    return `    ${key}: ${JSON.stringify(sqlText.replaceAll('\r\n', '\n'))},`;
  }),
);

const source = `// Generated by packages/db/scripts/bundle-migrations.ts (\`pnpm db:generate\`). Do not edit.
export const userMigrations = {
  journal: ${JSON.stringify(journal, null, 2).replaceAll('\n', '\n  ')},
  migrations: {
${entries.join('\n')}
  },
};
`;

await writeFile(target, source);
console.log(`Bundled ${entries.length} user migration(s) -> ${path.relative(root, target)}`);
